// 武将经验曲线
export function expToNextLevel(level: number): number {
  return Math.floor(100 * Math.pow(1.5, level - 1))
}

// 升级属性增长
export function levelUpStats(hero: Hero): Partial<Hero> {
  const newLevel = hero.level + 1
  return {
    level: newLevel,
    exp: hero.exp - hero.expToNext,
    expToNext: expToNextLevel(newLevel),
    stats: {
      martial: hero.stats.martial + hero.baseGrowth.martial,
      intelligence: hero.stats.intelligence + hero.baseGrowth.intelligence,
      command: hero.stats.command + hero.baseGrowth.command,
      politics: hero.stats.politics + hero.baseGrowth.politics,
      charisma: hero.stats.charisma + hero.baseGrowth.charisma,
    },
  }
}
